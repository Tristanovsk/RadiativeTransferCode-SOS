      END



C==============================================================================
C PROCEDURE: SOS_GLITTE
C ==========
C      This procedure computes, for an incidence (mup, phip) on waves,
C      the probability of reflection towards the direction (mu, phi).
C      The sea roughness depends on the wind speed.
C
C      Computations based on the Cox and Munk theory (1954).
C
C
C Description of parameters
C --------------------------
C     SIG	  (double)  (I)  Square of the parameter Sigma of the
C      			   Cox and Munk theory.
C     C0	  (double)  (I)  Absolute value of the cosine of the incidence
C      			   zenith angle (mup).
C     C1	  (double)  (I)  Absolute value of the cosine of the emergence
C     			          zenith angle (mu).
C     PHI	  (double)  (I)  Relative azimuth between the emergence direction
C                              and the incidence direction phi - phip (in radians).
C     P	  (double)  (O)  Probability of reflection towards the direction (mu, phi).
C
C Common used:
C --------------
C None
C
C Error cases:
C ------------
C None
C
C==============================================================================
      SUBROUTINE SOS_GLITTE(SIG,C0,C1,PHI,P)
       
      IMPLICIT NONE
      
C* Definition of variables
C*-----------------------------------------     
      DOUBLE PRECISION SIG !Square of the parameter Sigma of the Cox and Munk theory.

      DOUBLE PRECISION C0 !Absolute value of the cosine of the incidence zenith angle (mup).
      DOUBLE PRECISION C1 !Absolute value of the cosine of the emergence zenith angle (mu).
      DOUBLE PRECISION PHI !Relative azimuth between the emergence direction and the incidence direction phi - phip (in radians).
      
      DOUBLE PRECISION P !Probability of reflection towards the direction (mu, phi).
      
      DOUBLE PRECISION X1
      DOUBLE PRECISION X2
      DOUBLE PRECISION X3
      DOUBLE PRECISION C0N ! Cosine of the zenith angle of the normal to the wave facet.
      DOUBLE PRECISION XXX
      
      DOUBLE PRECISION PP

       
C* Processing
C--------------
       X1=DSQRT(1-C1**2)-DCOS(PHI)*DSQRT(1-C0**2)
       X2= DSQRT(1-C0**2)*DSIN(PHI)
       X3=C0+C1
       C0N=(X3/(DSQRT(X1**2+X2**2+X3**2)))
       XXX=(-(1-C0N**2)/(SIG*C0N**2))
       
       IF (XXX.LT.-100) THEN
           P=0.
       ELSE
           PP=(1/SIG)*DEXP(XXX)
           P=PP/(4*C1*C0N**4)
       ENDIF     
 
       RETURN
       END  	!END OF PROCEDURE SOS_GLITTE



C==============================================================================
C PROCEDURE: SOS_ANGLE
C ==========
C      This procedure computes:
C         _ the cosine of the scattering angle between the solar incidence
C	     direction and the viewing direction.
C	   _ the cosine of the rotation angle KI'.
C
C Description of parameters
C --------------------------
C       C0      (double)  (I) Absolute value of the cosine of the solar zenith angle.
C       C1	  (double)  (I) Absolute value of the cosine of the viewing zenith angle.
C       PHI	  (double)  (O) Relative azimuth between the viewing direction
C                             and the Sun direction (in radians).
C       COSKIP  (double)  (O)  Cosine of the rotation angle Ki'.
C       COSDIF  (double)  (O)  Cosine of the scattering angle.
C
C Common used:
C --------------
C None
C
C Error cases:
C ------------
C None
C
C==============================================================================
      SUBROUTINE SOS_ANGLE(C0,C1,PHI,COSKIP,COSDIF)
      
      IMPLICIT NONE

C* Definition of variables
C*----------------------------------------
      DOUBLE PRECISION C0 !Absolute value of the cosine of the solar zenith angle.
      DOUBLE PRECISION C1 !Absolute value of the cosine of the viewing zenith angle.
      DOUBLE PRECISION PHI !Relative azimuth between the viewing direction and the Sun direction (in radians).
      
      DOUBLE PRECISION COSKIP !(O) Cosine of the rotation angle Ki'.
      DOUBLE PRECISION COSDIF !(O) Cosine of the scattering angle.
            				 
      DOUBLE PRECISION S ! 1 or -1.
      DOUBLE PRECISION Z	

C* Processing
C--------------         
      S=1.
      IF (DSIN(PHI).GT.0.D+00)  S=-1.
      
      COSDIF=-C0*C1+DSQRT(1-C0**2)*DSQRT(1-C1**2)*DCOS(PHI)
      Z=S*(DSQRT(1-COSDIF**2))*(DSQRT(1-C1*C1))
      COSKIP=0.
      
      IF (DABS(Z).GT. CTE_SEUIL_Z)  COSKIP=(C1*COSDIF+C0)/Z
      
      RETURN
      END  	!END OF PROCEDURE SOS_ANGLE





C==============================================================================
C PROCEDURE: SOS_REFLEX
C ==========
C      This procedure computes the elements R11, R12 and R33 of the Fresnel
C      reflection matrix expressed in a frame tied to the reflection plane.
C
C      The Fresnel matrix is:
C                  | R11(teta)  R12(teta)    0      |
C         F(teta)= | R12(teta)  R11(teta)    0      |
C                  |    0          0      R33(teta) |
C
C         with:
C           _ teta : reflection angle with respect to the normal of the interface,
C           _ R11(teta) = 0.5 * (RL*RL + RR*RR),
C           _ R12(teta) = 0.5 * (RL*RL - RR*RR),
C           _ R33(teta) = RL*RR,
C
C         The relative refractive index of the interface, between the reflection
C         medium and the transmission medium, is IND.
C
C         RL and RR are computed from IND and teta by:
C           _ RL : the parallel reflection coefficient
C
C               RL(teta) = [ IND**2 * cos(teta) - SQRT(IND**2 - sin(teta)**2) ]
C                        / [ IND**2 * cos(teta) + SQRT(IND**2 - sin(teta)**2) ]
C
C           _ RR : the perpendicular reflection coefficient
C
C               RR(teta) = [ cos(teta) - SQRT(IND**2 - sin(teta)**2) ]
C                        / [ cos(teta) + SQRT(IND**2 - sin(teta)**2) ]
C
C
C
C Description of parameters
C --------------------------
C       COSDIF	  (double)  (I)  Cosine of the scattering angle.
C       IND	  (double)  (I)  relative refractive index
C     				 (water / air for a reflection on the sea).
C       R11	  (double)  (O) Element of the Fresnel reflection matrix.
C       R12	  (double)  (O) same as R11
C       R33	  (double)  (O) same as R11
C
C
C Common used:
C --------------
C None
C
C Error cases:
C ------------
C None
C
C==============================================================================
      SUBROUTINE SOS_REFLEX(COSDIF,IND,R11,R12,R33)
      
      IMPLICIT NONE      

C* Definition of variables
C*---------------------------    
      DOUBLE PRECISION COSDIF ! Cosine of the scattering angle.
      
      DOUBLE PRECISION IND !relative refractive index (water / air for a reflection on the sea).
      
      DOUBLE PRECISION R11 !Elements of the Fresnel reflection matrix.
      DOUBLE PRECISION R12
      DOUBLE PRECISION R33
        
      DOUBLE PRECISION IND2 ! Square of the relative refractive index.
				
      DOUBLE PRECISION COSW ! Cosine of the reflection angle W
                            ! (incidence angle with respect to the normal of the interface)
      
      DOUBLE PRECISION V ! Square sine of W.
      DOUBLE PRECISION X	
      
      DOUBLE PRECISION RL ! Parallel reflection coefficient.
      DOUBLE PRECISION RR ! Perpendicular reflection coefficient.
      

C* Processing
C--------------     
      IND2=IND*IND
      
      COSW=DSQRT(.5*(1-COSDIF))
      V=.5*(1+COSDIF)
      X=DSQRT(IND2-V)     
      RL=(IND2*COSW-X)/(IND2*COSW+X)
      RR=(COSW-X)/(COSW+X)
      R11=(RL**2+RR**2)/2.
      R12=(RL**2-RR**2)/2.
      R33=RR*RL
      RETURN
      END  	!END OF PROCEDURE SOS_REFLEX




C==============================================================================
C PROCEDURE: SOS_MATRIC
C ==========
C      This procedure computes the elements M11, M21 and M31 of the reflection
C      matrix expressed in a frame tied to the meridian plane (1st column).
C      
C
C Description of parameters
C --------------------------
C       COSKIP  (double)  (I) Cosine of the rotation angle KI'
C       R11	  (double)  (I) Element of the Fresnel reflection matrix
C     				  in the frame tied to the reflection plane.
C       R12	  (double)  (I) same as R11
C       M11	  (double)  (O) Element of the reflection matrix in the
C                             frame tied to the meridian plane.
C       M21	  (double)  (O) same as M11
C       M31	  (double)  (O) same as M11
C  
C
C Common used:
C --------------
C None
C
C Error cases:
C ------------
C None
C
C==============================================================================
      SUBROUTINE SOS_MATRIC(COSKIP,R11,R12,M11,M21,M31)
      
      IMPLICIT NONE

C* Definition of variables
C*------------------------------------------------   
      DOUBLE PRECISION COSKIP !Cosine of the rotation angle KI'.
      
      DOUBLE PRECISION R11 ! Elements of the Fresnel reflection matrix in the frame tied to the reflection plane.
      DOUBLE PRECISION R12 
      
      DOUBLE PRECISION M11 !Element of the reflection matrix in the frame tied to the meridian plane.
      DOUBLE PRECISION M21
      DOUBLE PRECISION M31
   
      DOUBLE PRECISION C2 ! Cosine of 2*KI'.
      DOUBLE PRECISION S2 ! Sine of 2*KI'.
      DOUBLE PRECISION X

C* Processing
C--------------               
      X=1.-DABS(COSKIP)
      C2=1.
      S2=0.
      IF (X.GE.CTE_SEUIL_X) THEN
         C2=2.*COSKIP*COSKIP-1.
         S2=2.*COSKIP*DSQRT(1.-COSKIP*COSKIP)
      ENDIF
      
      IF (COSKIP.EQ.0.D+00) R12=0.
      
      M11=R11
      M21=C2*R12
      M31=S2*R12
      
      RETURN
      END  	!END OF PROCEDURE SOS_MATRIC




C==============================================================================
C PROCEDURE: SOS_OUTPUT_HEADER
C ==========
C      This procedure writes header information in the result files
C      of the radiance field simulation.
C      
C
C Description of parameters
C --------------------------
C       FICID	  (I4)     (I) : Index of the file opened for writing
C       UPDOWN  (I4)     (I) : Index for upward (1) or downward field
C       PHI1    (double) (I) : Azimuth direction defined by the user
C       PHI2    (double) (I) : Direction PHI1 + PI
C       ZALT    (double) (I) : Altitude of the level of the output radiance
C
C Common used:
C --------------
C None
C
C Error cases:
C ------------
C None
C
C==============================================================================
      SUBROUTINE SOS_OUTPUT_HEADER(FICID, UPDOWN, PHI1, PHI2, ZALT)
      
      IMPLICIT NONE

C* Definition of variables

      INTEGER FICID	
      INTEGER UPDOWN ! Index specifying upward (1) or downward (other) field
      DOUBLE PRECISION PHI1 ! Relative azimuth (radians)
      DOUBLE PRECISION PHI2 ! Relative azimuth PHI1 + Pi (radians)
      DOUBLE PRECISION ZALT ! Altitude of the radiance (km)

C* Processing
C--------------    

      IF (UPDOWN.EQ.1) THEN
          WRITE(FICID,'(A55)') 
     &    '# UPWARD RADIANCE FIELD VERSUS THE VIEWING ZENITH ANGLE'
      ELSE
          WRITE(FICID,'(A57)') 
     &    '# DOWNWARD RADIANCE FIELD VERSUS THE VIEWING ZENITH ANGLE'
      ENDIF

      WRITE(FICID,'(A43)') 
     &    '# (RELATIVE AZIMUTH AND ALTITUDE ARE FIXED)'
      WRITE(FICID,'(A102)') '#--------------------------------------'//
     &'---------------------------------------------------------------'
	  
      WRITE(FICID,'(A30)')  '# Relative azimuth (degrees) :'
      WRITE(FICID,'(A1)')   '#'
      WRITE(FICID,'(A36)')  '#      Relative azimuth convention :'

      IF (UPDOWN.EQ.1) THEN
         WRITE(FICID,'(A58)')  
     &   '#        180° <-> Satellite and Sun in the same half-plane'
         WRITE(FICID,'(A96)')  
     &     '#          0° <-> Satellite and Sun in opposite'//
     &     ' half-planes with respect to the zenith direction'          
      ELSE
          WRITE(FICID,'(A66)')  
     &     '#        180° <-> Viewing direction and Sun'//
     &     ' in the same half-plane'
         WRITE(FICID,'(A104)')  
     &     '#          0° <-> Viewing direction and Sun in opposite'//
     &     ' half-planes with respect to the zenith direction'              
      ENDIF

      WRITE(FICID,'(A1)')   '#'
      WRITE(FICID,'(A45)')
     &	    '#      Simulated relative azimuth (degrees) :'
      WRITE(FICID,10)  '#          for VZA < 0 (sign convention):',
     &	                  PHI2
      WRITE(FICID,10)  '#          for VZA > 0 (sign convention):',
     &	                  PHI1

      WRITE(FICID,'(A1)')   '#'
      WRITE(FICID,20)  
     &'# Value of the selected altitude for the output (km) :', ZALT
     
      WRITE(FICID,'(A1)')   '#'
      WRITE(FICID,'(A22)') '# Columns parameters :'
      WRITE(FICID,'(A48)')  
     &'#   VZA     :  Viewing Zenith Angle (in degrees)'
      WRITE(FICID,'(A44)')  
     &'#   SCA_ANG :  Scattering angle (in degrees)'
      WRITE(FICID,'(A64)')  
     &'#   I       :  Stokes parameter I at output altitude z'// 
     &' (in sr-1)'
      WRITE(FICID,'(A85)')  
     &'#              normalised to the extraterrestrial solar'// 
