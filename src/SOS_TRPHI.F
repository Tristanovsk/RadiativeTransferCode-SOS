#define INCTE_VALEUR_INDEF -999.


C============================================================================
C PROCEDURE: SOS_TRPHI_OPTION
C ==========
C
C      This procedure recombines the Fourier series of the parameters I, Q and U
C      for one relative azimuth value or a set of relative azimuth values,
C      for the upward and downward fields.
C
C      The polarisation state is computed: degree of polarisation, polarisation angle.
C      
C      If ITRPHI = 1, the viewing plane is obtained for PHIos
C                     (relative azimuth with respect to the solar azimuth)
C         Convention:
C             The viewing angle is positive for the half plane PHI = PHIos.
C	       The viewing angle is negative for the half plane PHI = PHIos + 180.
C
C
C      If ITRPHI = 2, a polar diagram is obtained versus the viewing
C      angle (teta) and the azimuth angle (phi):
C
C         X =  phi    ,   Y = teta    ,   I  ,  Q  ,  U
C
C	   The viewing angle increases from the centre to the edge of the image.
C
C         The user chooses the azimuth sampling step (PAS_PHI).
C
C
C      For the flat sea case, the code adds the reflection of the direct solar
C      radiance, travelling down from TOA to the surface, attenuated by the atmosphere.
C      Reflection symmetric to the solar incidence direction with respect to the zenith.
C      NB: The solar radiance is computed for a solar irradiance at TOA
C           equal to PI, for a mean Earth-Sun distance,
C           the constant CTE_SOLAR_DISC_SOLID_ANGLE giving the solid angle of the apparent
C           solar disc for the mean Earth-Sun distance.
C
C
C Description of parameters
C --------------------------
C     NBMU (I4) : (I) Number of actually useful (positive) angles
C
C	 RMU(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) (DOUBLE) : (I) Cosines of the angles.
C     GA(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) (DOUBLE)  : (I) Weights of the angles.
C
C     FICHOS   (CHARACTER*CTE_LENFIC2)  (I) :  Name of the OS result file
C				  (directory + file name + extension)
C     TAU (double)    (I) : Total optical thickness of the atmosphere
C                          (possibly truncated).
C     TAUOUT (double) (I) : Optical thickness at the output level of the results for the
C                           upward field.
C     AT_DIR(CTE_OS_NBMU_MAX) (double) (I) : Direct transmission of the
C                           solar beam TOA -> surface -> output level,
C                           along the direction J (see SOS_TRPHI_MULTI).
C     ZOUT (DOUBLE)   (I) : Output altitude of the radiation field
C			         -1 : 300 km for the upward field, 0 km for the downward field.
C                             ZOUT between 0 and 300 km: altitude for the upward and downward fields.
C     IGLI  (I4)      (I) : Glitter option:  0 : no Glitter.
C                                                1 : Glitter computation.
C     N0  (I4)        (I) : Number of the Gauss mu for the solar zenith angle.
C			     (complementary angle: mus = -rmu(N0))
C			      (N0 > 0 => to take it into account).
C     WIND (double)   (I) : Wind speed in m/s.
C     IND_SURF (double) (I) : Relative refractive index surface / air.
C     IFRESNEL  (I4)  (I) : Option for the computation of the Fresnel reflection on a flat sea:
C                             0 : no reflection on a flat sea.
C                             1 : computation of the Fresnel reflection on a flat sea.
C     IROUJEAN (I4)   (I) : Option for the computation of the Roujean reflection
C                             0 : no reflection by the Roujean BRDF.
C                             1 : computation of the reflection by the Roujean BRDF.
C     K0_ROUJEAN (double) (I) : Parameter k0 of the Roujean BRDF.
C     K1_ROUJEAN (double) (I) : Parameter k1 of the Roujean BRDF.
C     K2_ROUJEAN (double) (I) : Parameter k2 of the Roujean BRDF.
C     IRONDEAUX (I4)  (I) : Option for the computation of the Rondeaux reflection
C                             0 : no reflection by the Rondeaux BPDF.
C                             1 : computation of the reflection by the Rondeaux BPDF.
C     IBREON (I4)     (I) : Option for the computation of the Breon reflection
C                             0 : no reflection by the Breon BPDF.
C                             1 : computation of the reflection by the Breon BPDF.
C     INADAL (I4)     (I) : Option for the computation of the Nadal reflection
C                             0 : no reflection by the Nadal BPDF.
C                             1 : computation of the reflection by the Nadal BPDF.
C     ALPHA_NADAL (double)  (I) : Parameter alpha of the Nadal model.
C     BETA_NADAL (double)  (I) : Parameter beta of the Nadal model.
C     IMAIGNAN (I4)     (I) : Option for the computation of the Maignan reflection
C                             0 : no reflection by the Maignan BPDF.
C                             1 : computation of the reflection by the Maignan BPDF.
C     COEF_C_MAIGNAN  (double)  (I) : Parameter C*exp(-NDVI) of the Maignan model.
C     ITRPHI (I4)     (I) : Index of output type.
C     PHIOS (double)  (I) : Relative azimuth in degrees (for ITRPHI=1).
C     PAS_PHI (I4)    (I) : Azimuth step in degrees (for ITRPHI=2)
C                           Integer value.
C     IPOLAR  (I4)   (I) : Option for simulation without polarisation.
C      			   0 : computations without polarisation.
C			          1 : normal computations with polarisation.
C
C     PHI_FIN(0:360)	 (double) : (O) Table of the relative azimuths of the output field
C     THETA_FIN(0:CTE_OS_NBMU_MAX) (double) : (O) Table of the viewing zenith angles of the output field
C     SCA_UP_FIN(0:360,0:CTE_OS_NBMU_MAX) (double) : (O) Table of the scattering angles for the output upward field
C                                                        versus Phi and Thetav
C     I_UP_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)   : (O) Table of the I values for the output upward field
C     Q_UP_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)   : (O) Table of the Q values for the output upward field
C     U_UP_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)   : (O) Table of the U values for the output upward field
C     POL_ANG_UP_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)  : (O) Table of the polarisation angles for the output upward field
C     POL_RATE_UP_FIN(0:360,0:CTE_OS_NBMU_MAX) (double) : (O) Table of the degrees of polarisation for the output upward field
C     L_POL_UP_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)    : (O) Table of the polarised radiance values for the output upward field
C
C     SCA_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) (double) : (O) Table of the scattering angles for the output downward field
C                                                          versus Phi and Thetav
C     I_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)   : (O) Table of the I values for the output downward field
C     Q_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)   : (O) Table of the Q values for the output downward field
C     U_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)   : (O) Table of the U values for the output downward field
C     POL_ANG_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)  : (O) Table of the polarisation angles for the output downward field
C     POL_RATE_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) (double) : (O) Table of the degrees of polarisation for the output downward field
C     L_POL_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) (double)    : (O) Table of the polarised radiance values for the output downward field
C
C     IER  (I4)       (O) : Error code =0 if no error, =-1 otherwise
C
C
C Environment variable
C ------------------------
C   None
C
C
C Description of the files used
C ---------------------------------
C
C   -->Content of the OS result file
C       Unformatted binary file, created by SOS_OS
C       It contains the Stokes parameters Q, U and I for an order S
C       of the Fourier series expansion, versus the angle mu
C       (double precision values).
C
C Common used:
C --------------
C None
C
C Error cases:
C ------------
C     -Opening of a file
C       Error if the OS result file does not exist
C
C     Message displayed on screen, the routine stops its computations and
C     returns status -1 to the calling program
C     
C  Routines used by the procedure:
C ------------------------------------
C  This program calls the routines:
C      - SOS_TRPHI
C      - SOS_POLAR
C
C==============================================================================
  
      SUBROUTINE SOS_TRPHI_OPTION(NBMU,RMU,GA,
     &     FICHOS,TAU,TAUOUT,AT_DIR,ZOUT,
     &     IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &     IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &     IRONDEAUX,IBREON,
     &     INADAL,ALPHA_NADAL,BETA_NADAL,
     &     IMAIGNAN,COEF_C_MAIGNAN,
     &     ITRPHI,PHIOS,PAS_PHI,IPOLAR,
     &     PHI_FIN, THETA_FIN, 
     &     SCA_UP_FIN, I_UP_FIN, Q_UP_FIN, U_UP_FIN,
     &     POL_ANG_UP_FIN, POL_RATE_UP_FIN, L_POL_UP_FIN,
     &     SCA_DOWN_FIN, I_DOWN_FIN, Q_DOWN_FIN, U_DOWN_FIN,
     &     POL_ANG_DOWN_FIN, POL_RATE_DOWN_FIN, L_POL_DOWN_FIN,
     &     IER)

   	 	
      IMPLICIT NONE

C* Definition of variables
C*-----------------------------------------
      DOUBLE PRECISION TAU ! Total optical thickness of the atmosphere (possibly truncated).

      DOUBLE PRECISION TAUOUT ! Optical thickness at the output level of the results for the upward field.

      DOUBLE PRECISION AT_DIR(CTE_OS_NBMU_MAX) ! Direct transmission of the solar beam
                                     ! TOA -> surface -> output level, direction J

      INTEGER*4 NPHI ! Number of azimuths recombined in one pass
      DOUBLE PRECISION PHI_LIST(361) ! Relative azimuths (radians)
      DOUBLE PRECISION XITM(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,361) ! I(mu,phi)
      DOUBLE PRECISION XQTM(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,361) ! Q(mu,phi)
      DOUBLE PRECISION XUTM(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,361) ! U(mu,phi)
      DOUBLE PRECISION ANGM(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,361) ! Scat. angle

      DOUBLE PRECISION ZOUT ! Output altitude of the radiation field
                            ! If -1: output at 300 km for the upward field, 0 km for the downward field.
                            ! If between 0 and 300 km: output at ZOUT for the upward and downward fields.
						
      DOUBLE PRECISION WIND ! Wind speed in m/s.
      DOUBLE PRECISION IND_SURF ! Relative refractive index surface / air.
      DOUBLE PRECISION K0_ROUJEAN ! Parameter k0 of the Roujean BRDF model.
      DOUBLE PRECISION K1_ROUJEAN ! Parameter k1 of the Roujean BRDF model.
      DOUBLE PRECISION K2_ROUJEAN ! Parameter k2 of the Roujean BRDF model.
      DOUBLE PRECISION ALPHA_NADAL ! Parameter alpha of the Nadal BPDF model.
      DOUBLE PRECISION BETA_NADAL ! Parameter beta of the Nadal BPDF model.
      DOUBLE PRECISION COEF_C_MAIGNAN ! Parameter C*exp(-NDVI) of the Maignan model.
      DOUBLE PRECISION PHIOS ! Relative azimuth in degrees (for ITRPHI=1).
      
      DOUBLE PRECISION TETA ! Viewing angle (in degrees).
      DOUBLE PRECISION PHI ! Relative azimuth (in radians).
      DOUBLE PRECISION PHI1, PHI2 ! Relative azimuth (in radians).
      
      DOUBLE PRECISION XIT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) ! Stokes parameter I
                                                             ! versus mu for the azimuth phi.
                                                             !    mu < 0 : downward field.
                                                             !    mu > 0 : upward field.
      DOUBLE PRECISION XQT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) ! Stokes parameter Q.
      DOUBLE PRECISION XUT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) ! Stokes parameter U.
   
      DOUBLE PRECISION XI !  Value of the Stokes parameter I for an angle
      DOUBLE PRECISION XQ
      DOUBLE PRECISION XU   	  
      
      DOUBLE PRECISION RMU(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) !Array of the Gauss (and user) angles.
      DOUBLE PRECISION GA(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)  !Weights of the Gauss (and user) angles.

      DOUBLE PRECISION ANGDIFF(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) !Scattering angles


      DOUBLE PRECISION XAN ! Polarisation angle (degrees)
      DOUBLE PRECISION LPOL ! Polarised intensity normalised to the solar irradiance at TOA
      DOUBLE PRECISION TPOL ! Degree of polarisation in %.

      CHARACTER*CTE_LENFIC2 FICHOS !Name of the OS result file

      INTEGER*4 IGLI ! Glitter option: 0 : no Glitter.
                     !                     1 : Glitter computation.

      INTEGER*4 IFRESNEL ! Index specifying whether the simulations include the Fresnel reflection on a flat sea:
                         !    1 => for a computation of the Fresnel reflection.
                         !    Otherwise => not taken into account.
	
      INTEGER*4 IROUJEAN ! Index specifying whether the simulations include the reflection by the Roujean BRDF:
                         !    1 => for a computation with the Roujean BRDF.
                         !    Otherwise => not taken into account.
      
      INTEGER*4 IRONDEAUX ! Index specifying whether the simulations include the reflection by the Rondeaux BPDF:
                          !    1 => for a computation with the Rondeaux BPDF.
                          !    Otherwise => not taken into account.
			  
      INTEGER*4 IBREON ! Index specifying whether the simulations include the reflection by the Breon BPDF:
                       !    1 => for a computation with the Breon BPDF.
                       !    Otherwise => not taken into account.
			  
      INTEGER*4 INADAL ! Index specifying whether the simulations include the reflection by the Nadal BPDF:
                       !    1 => for a computation with the Nadal BPDF.
                       !    Otherwise => not taken into account.
			  
      INTEGER*4 IMAIGNAN ! Index specifying whether the simulations include the reflection by the Maignan BPDF:
                         !    1 => for a computation with the Maignan BPDF.
                         !    Otherwise => not taken into account.
			             
      INTEGER*4 N0 ! Number of the Gauss mu for the solar zenith angle.
                   ! (complementary angle: mus = -rmu(N0))
                   ! (N0 > 0 => to take it into account).

      INTEGER*4 ITRPHI ! Index of output type.
                       !   1 =>  Viewing plane for one azimuth value.
                       !   2 =>  Polar diagram versus the azimuth and viewing directions.
			      
      INTEGER*4 PAS_PHI ! Azimuth step in degrees (for ITRPHI=2, integer value)
      
      INTEGER*4 IPOLAR ! Option for simulation without polarisation.
                       ! 0 : computations without polarisation.
                       ! 1 : normal computations with polarisation.
			      
      INTEGER*4 IER ! error code =0 if no error, =-1 otherwise
      INTEGER*4 J ! Index of the array of Gauss angles.
      INTEGER*4 IPHI ! Loop index on the relative azimuth.
      INTEGER*4 NBMU ! number of useful angles
			
      INTEGER*4 I  ! row index of the arrays SCA_FIN, I_FIN, Q_FIN, U_FIN, POL_ANG_FIN, POL_RATE_FIN, L_POL_FIN
      INTEGER*4 JJ ! column index of the arrays THETA_FIN, SCA_FIN, I_FIN, Q_FIN, U_FIN, POL_ANG_FIN, POL_RATE_FIN, L_POL_FIN
      INTEGER*4 IP ! row index of the arrays SCA_FIN, I_FIN, Q_FIN, U_FIN, POL_ANG_FIN, POL_RATE_FIN, L_POL_FIN
       
   
      DOUBLE PRECISION PHI_FIN(0:360)		   !Table of the relative azimuths of the output field
      DOUBLE PRECISION THETA_FIN(0:CTE_OS_NBMU_MAX) !Table of the viewing zenith angles of the output field
            
      DOUBLE PRECISION SCA_UP_FIN(0:360,0:CTE_OS_NBMU_MAX)   !Table of the scattering angles for the output upward field
      DOUBLE PRECISION SCA_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) !Table of the scattering angles for the output downward field

      DOUBLE PRECISION I_UP_FIN(0:360,0:CTE_OS_NBMU_MAX)     !Table of the I values for the output upward field
      DOUBLE PRECISION Q_UP_FIN(0:360,0:CTE_OS_NBMU_MAX)     !Table of the Q values for the output upward field
      DOUBLE PRECISION U_UP_FIN(0:360,0:CTE_OS_NBMU_MAX)     !Table of the U values for the output upward field
      DOUBLE PRECISION I_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX)   !Table of the I values for the output downward field
      DOUBLE PRECISION Q_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX)   !Table of the Q values for the output downward field
      DOUBLE PRECISION U_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX)   !Table of the U values for the output downward field
      
      DOUBLE PRECISION POL_ANG_UP_FIN(0:360,0:CTE_OS_NBMU_MAX)   !Table of the polarisation angles for the output upward field
      DOUBLE PRECISION POL_ANG_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) !Table of the polarisation angles for the output downward field
     
      DOUBLE PRECISION POL_RATE_UP_FIN(0:360,0:CTE_OS_NBMU_MAX)   !Table of the degrees of polarisation for the output upward field
      DOUBLE PRECISION POL_RATE_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) !Table of the degrees of polarisation for the output downward field
  
      DOUBLE PRECISION L_POL_UP_FIN(0:360,0:CTE_OS_NBMU_MAX)   !Table of the polarised radiance values for the output upward field
      DOUBLE PRECISION L_POL_DOWN_FIN(0:360,0:CTE_OS_NBMU_MAX) !Table of the polarised radiance values for the output downward field

      	
C* Initialisation of the error code
C------------------------------------------------------
      IER=0
     
      
C* Output of one azimuth plane
C------------------------------------------------------
      IF(ITRPHI.EQ.1) THEN

         !Half plane PHIos + 180 degrees: negative viewing angles by convention
         !----------------------------------------------------------------------
         !Both half planes are recombined in one pass
         NPHI=2
         PHI_LIST(1)=INCTE_PI+PHIOS*INCTE_PI/180.D+00
         PHI_LIST(2)=PHIOS*INCTE_PI/180.D+00
         CALL SOS_TRPHI_MULTI(FICHOS,NBMU,RMU,AT_DIR,NPHI,PHI_LIST,
     &        IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &        IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &        IRONDEAUX,IBREON,
     &        INADAL,ALPHA_NADAL,BETA_NADAL,
     &        IMAIGNAN,COEF_C_MAIGNAN,
     &        IPOLAR,XITM,XQTM,XUTM,ANGM,IER)
         IF (IER.NE.0) GOTO 9999   ! error case
         CALL SOS_TRPHI_COLUMN(NBMU,1,XITM,XQTM,XUTM,ANGM,
     &                         XIT,XQT,XUT,ANGDIFF)

         PHI_FIN(0) = PHIOS + 180

         DO J=NBMU,1,-1
            
            TETA=DACOS(RMU(J))*180.D+00/INCTE_PI
            
            !Recording for the upward field
            !------------------------------------
            XI = XIT(J)
            XQ = XQT(J)
            XU = XUT(J)
            CALL SOS_POLAR(XI,XQ,XU,XAN,TPOL,LPOL)

C            JJ=NBMU-J
	    JJ=J-1
	    
            THETA_FIN(JJ) = -TETA
            SCA_UP_FIN(0, JJ) = ANGDIFF(J)

            I_UP_FIN(0, JJ) = XI
            Q_UP_FIN(0, JJ) = XQ
            U_UP_FIN(0, JJ) = XU
            POL_ANG_UP_FIN(0, JJ) = XAN
            POL_RATE_UP_FIN(0, JJ) = TPOL
            L_POL_UP_FIN(0, JJ) = LPOL
           
            !Recording for the downward field
            !---------------------------------------
            XI = XIT(-J)
            XQ = XQT(-J)
            XU = XUT(-J)
            CALL SOS_POLAR(XI,XQ,XU,XAN,TPOL,LPOL)

            THETA_FIN(JJ) = -TETA
            SCA_DOWN_FIN(0, JJ) = ANGDIFF(-J)
            
            I_DOWN_FIN(0, JJ) = XI
            Q_DOWN_FIN(0, JJ) = XQ
            U_DOWN_FIN(0, JJ) = XU
            POL_ANG_DOWN_FIN(0, JJ) = XAN
            POL_RATE_DOWN_FIN(0, JJ) = TPOL
            L_POL_DOWN_FIN(0, JJ) = LPOL
	     	    
         ENDDO
 

	    
         !Half plane PHIos: positive viewing angles by convention
         !---------------------------------------------------------
         CALL SOS_TRPHI_COLUMN(NBMU,2,XITM,XQTM,XUTM,ANGM,
     &                         XIT,XQT,XUT,ANGDIFF)

         PHI_FIN(0) = PHIOS 
	 
         DO J=1,NBMU
            
            TETA=DACOS(RMU(J))*180.D+00/INCTE_PI

            !Recording for the upward field
            !------------------------------------
            XI = XIT(J)
            XQ = XQT(J)
            XU = XUT(J)
            CALL SOS_POLAR(XI,XQ,XU,XAN,TPOL,LPOL)

            JJ=J-1
	    
            THETA_FIN(JJ) = TETA
            SCA_UP_FIN(1, JJ) = ANGDIFF(J)
            
            I_UP_FIN(1, JJ) = XI
            Q_UP_FIN(1, JJ) = XQ
            U_UP_FIN(1, JJ) = XU
            POL_ANG_UP_FIN(1, JJ) = XAN
            POL_RATE_UP_FIN(1, JJ) = TPOL
            L_POL_UP_FIN(1, JJ) = LPOL
        
            !Recording for the downward field
            !---------------------------------------
            XI = XIT(-J)
            XQ = XQT(-J)
            XU = XUT(-J)
            CALL SOS_POLAR(XI,XQ,XU,XAN,TPOL,LPOL)

            THETA_FIN(JJ) = TETA
            SCA_DOWN_FIN(1, JJ) = ANGDIFF(-J)
            
            I_DOWN_FIN(1, JJ) = XI
            Q_DOWN_FIN(1, JJ) = XQ
            U_DOWN_FIN(1, JJ) = XU
            POL_ANG_DOWN_FIN(1, JJ) = XAN
            POL_RATE_DOWN_FIN(1, JJ) = TPOL
            L_POL_DOWN_FIN(1, JJ) = LPOL	    
         
         ENDDO	    

      ENDIF  !ITRPHI=1
      


C* Output of a polar diagram
C---------------------------------
      IF(ITRPHI.EQ.2) THEN        

         !All the azimuths are recombined in one pass
         NPHI=0
         DO IPHI=0,360,PAS_PHI
            NPHI=NPHI+1
            PHI_LIST(NPHI) = INCTE_PI * IPHI / 180.D+00
         ENDDO
         CALL SOS_TRPHI_MULTI(FICHOS,NBMU,RMU,AT_DIR,NPHI,PHI_LIST,
     &        IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &        IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &        IRONDEAUX,IBREON,
     &        INADAL,ALPHA_NADAL,BETA_NADAL,
     &        IMAIGNAN,COEF_C_MAIGNAN,
     &        IPOLAR,XITM,XQTM,XUTM,ANGM,IER)
         IF (IER.NE.0) GOTO 9999   ! error case

         IP=0
	 
         DO IPHI=0,360,PAS_PHI
            
	    
            CALL SOS_TRPHI_COLUMN(NBMU,IP+1,XITM,XQTM,XUTM,ANGM,
     &                            XIT,XQT,XUT,ANGDIFF)
            
            PHI = dble(IPHI)
            DO J=1,NBMU
               TETA=DACOS(RMU(J))*180.D+00/INCTE_PI
               !Recording for the upward field
               !------------------------------------
               XI = XIT(J)
               XQ = XQT(J)
               XU = XUT(J)               
               CALL SOS_POLAR(XI,XQ,XU,XAN,TPOL,LPOL)

               PHI_FIN(IP) = PHI
               THETA_FIN(J-1) = TETA

               SCA_UP_FIN(IP, J-1) = ANGDIFF(J)
               
               I_UP_FIN(IP, J-1) = XI
               Q_UP_FIN(IP, J-1) = XQ
               U_UP_FIN(IP, J-1) = XU
               POL_ANG_UP_FIN(IP, J-1) = XAN
               POL_RATE_UP_FIN(IP, J-1) = TPOL
               L_POL_UP_FIN(IP, J-1) = LPOL

               !Nominal case: downward field for all the angles
               XI = XIT(-J)
               XQ = XQT(-J)
               XU = XUT(-J)
               CALL SOS_POLAR(XI,XQ,XU,XAN,TPOL,LPOL) 	 

               SCA_DOWN_FIN(IP, J-1) = ANGDIFF(-J)
               
               I_DOWN_FIN(IP, J-1) = XI
               Q_DOWN_FIN(IP, J-1) = XQ
               U_DOWN_FIN(IP, J-1) = XU
               POL_ANG_DOWN_FIN(IP, J-1) = XAN
               POL_RATE_DOWN_FIN(IP, J-1) = TPOL
               L_POL_DOWN_FIN(IP, J-1) = LPOL
      
             ENDDO              !MU
	     
	     !Increment of the index PHI
	     IP=IP+1
	     
	  ENDDO                 !PHI
          
      ENDIF !ITRPHI=2
      
C* Nominal end
C-------------------
      GOTO 9999
      
C* Error case: return of status -1 to the calling program
C----------------------------------------------------------
  991 WRITE(6,*) "SOS_TRPHI_OPTION : Error while opening a file"
      IER=-1
      GOTO 9999
  992 WRITE(6,*) 
     & "SOS_TRPHI_OPTION : Error while reading or writing on a file"
      IER=-1
      GOTO 9999
      
      
 9999 CONTINUE


      RETURN  	
      END  	!END OF PROCEDURE SOS_OPTION_TRPHI




C==============================================================================
C PROCEDURE: SOS_TRPHI
C ==========
C      This procedure recombines the Fourier series decomposition of the
C      Stokes parameters I, Q and U for a fixed relative azimuth.
C      
C      It recomputes analytically the direct reflection on the sea
C      (glitter) removed from the OS computations to reduce the maximum
C      useful order of the decomposition.
C
C
C Description of parameters
C --------------------------
C     FICHOS   (CHARACTER*CTE_LENFIC2)  (I) : Name of the OS result file
C				  (directory + file name + extension)
C     NBMU (I4) : (I) Number of actually useful (positive) angles
C     RMU(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)  (double)   (I) : Array of the cosines of the angles.
C     TAU  (double)      (I) : Total optical thickness of the atmosphere
C                              (possibly truncated).
C     TAUOUT  (double)   (I) : Optical thickness at the output level
C                              of the results for the upward field.
C     PHI  (double)      (I) : Relative azimuth in radians.
C     IGLI  (I4)      (I) : Glitter option:  0 : no Glitter.
C                                                1 : Glitter computation.
C     N0  (I4)        (I) : Number of the Gauss mu for the solar zenith angle.
C			     (complementary angle: mus = -rmu(N0))
C			      (N0 > 0 => to take it into account).
C     WIND (double)   (I) : Wind speed in m/s.
C     IND_SURF (double) (I) : Relative refractive index surface / air.
C     IFRESNEL  (I4)  (I) : Option for the computation of the Fresnel reflection
C                           on a flat sea:
C                             0 : no reflection on a flat sea.
C                             1 : computation of the Fresnel reflection on a flat sea.
C     IROUJEAN (I4)   (I) : Option for the computation of the Roujean reflection
C                             0 : no reflection by the Roujean BRDF.
C                             1 : computation of the reflection by the Roujean BRDF.
C     K0_ROUJEAN (double) (I) : Parameter k0 of the Roujean BRDF.
C     K1_ROUJEAN (double) (I) : Parameter k1 of the Roujean BRDF.
C     K2_ROUJEAN (double) (I) : Parameter k2 of the Roujean BRDF.
C     IRONDEAUX (I4)  (I) : Option for the computation of the Rondeaux reflection
C                             0 : no reflection by the Rondeaux BPDF.
C                             1 : computation of the reflection by the Rondeaux BPDF.
C     IBREON (I4)     (I) : Option for the computation of the Breon reflection
C                             0 : no reflection by the Breon BPDF.
C                             1 : computation of the reflection by the Breon BPDF.
C     INADAL (I4)     (I) : Option for the computation of the Nadal reflection
C                             0 : no reflection by the Nadal BPDF.
C                             1 : computation of the reflection by the Nadal BPDF.
C     ALPHA_NADAL (double) (I) : Parameter alpha of the Nadal model.
C     BETA_NADAL (double)  (I) : Parameter beta of the Nadal model.
C     IMAIGNAN (I4) : (I) Index specifying whether the simulations
C      			     include the Maignan reflection model:
C			      1 : for a Maignan BPDF computation (N0 > 0 must be used).
C			             Otherwise : not taken into account.
C     COEF_C_MAIGNAN  (double)  (I) : Parameter C*exp(-NDVI) of the Maignan model.
C     IPOLAR  (I4)    (I) : Option for simulation without polarisation.
C      			   0 : computations without polarisation.
C			          1 : normal computations with polarisation.
C     XIT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)  (double)   (O) :
C                              Stokes parameter I versus the angle mu,
C                              for the azimuth phi.
C                                 mu < 0 : downward field.
C                                 mu > 0 : upward field.
C     XQT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)  (double)   (O) : Stokes parameter Q.
C     XUT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)  (double)   (O) : Stokes parameter U.
C 
C     ANGDIFF(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)  (double)   (O) : Scattering angle for the
C                                                                 viewing angles.
C
C       IER  (I4)   (O) : error code =0 if no error, =-1 otherwise
C
C 
C Description of the files used
C ---------------------------------
C   -->Content of the OS result file
C       Unformatted binary file, created by SOS_OS
C       It contains the Stokes parameters Q, U and I for an order S
C       of the Fourier series expansion, versus the angle mu
C       (double precision values).
C
C
C Common used:
C --------------
C None
C     
C
C Error cases:
C ------------
C     -Opening of a file
C       Error if the OS result file does not exist
C     -Reading/writing in a file
C
C     Message displayed on screen, the routine stops its computations and
C     returns status -1 to the calling program
C
C     
C  Routines used by the procedure:
C ------------------------------------
C  This program calls the routines:
C      - SOS_GLITTE
C      - SOS_ANGLE
C      - SOS_REFLEX
C      - SOS_MATRIC
C      - SOS_CALC_F_ROUJEAN
C      - SOS_CALC_MAIGNAN
C
C==============================================================================

      SUBROUTINE SOS_TRPHI(FICHOS,NBMU,RMU,TAU,TAUOUT,PHI,
     &                     IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &                     IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &                     IRONDEAUX,IBREON,
     &                     INADAL,ALPHA_NADAL,BETA_NADAL,
     &                     IMAIGNAN,COEF_C_MAIGNAN,
     &                     IPOLAR,XIT,XQT,XUT,ANGDIFF,IER)

C     Since version 9.0, SOS_TRPHI is a single-azimuth wrapper of
C     SOS_TRPHI_MULTI: the direct transmission of the solar beam is
C     computed here from TAU and TAUOUT (Beer law), as before.

      IMPLICIT NONE

      CHARACTER*CTE_LENFIC2 FICHOS
      INTEGER*4 NBMU, N0, IER
      INTEGER*4 IGLI, IFRESNEL, IROUJEAN, IRONDEAUX, IBREON
      INTEGER*4 INADAL, IMAIGNAN, IPOLAR
      DOUBLE PRECISION RMU(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION TAU, TAUOUT, PHI
      DOUBLE PRECISION WIND, IND_SURF
      DOUBLE PRECISION K0_ROUJEAN, K1_ROUJEAN, K2_ROUJEAN
      DOUBLE PRECISION ALPHA_NADAL, BETA_NADAL, COEF_C_MAIGNAN
      DOUBLE PRECISION XIT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION XQT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION XUT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION ANGDIFF(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)

      DOUBLE PRECISION AT_DIR(CTE_OS_NBMU_MAX) ! Direct transmission
      DOUBLE PRECISION PHI_LIST(1)             ! Azimuth list (radians)
      DOUBLE PRECISION AT0                     ! TOA -> ground (sun)
      INTEGER*4 J

C* Direct transmission: incidence direction (TOA -> ground) and
C* emergence direction J (ground -> output level of the results).
      DO J=1,NBMU
         AT_DIR(J)=0.D+00
      ENDDO
      IF (N0.GT.0) THEN
         AT0=DEXP(-TAU/RMU(N0))
         DO J=1,NBMU
            AT_DIR(J) = AT0*DEXP(-(TAU-TAUOUT)/RMU(J))
         ENDDO
      ENDIF

      PHI_LIST(1)=PHI
      CALL SOS_TRPHI_MULTI(FICHOS,NBMU,RMU,AT_DIR,1,PHI_LIST,
     &                     IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &                     IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &                     IRONDEAUX,IBREON,
     &                     INADAL,ALPHA_NADAL,BETA_NADAL,
     &                     IMAIGNAN,COEF_C_MAIGNAN,
     &                     IPOLAR,XIT,XQT,XUT,ANGDIFF,IER)

      RETURN  	!END OF PROCEDURE SOS_TRPHI
      END



C==============================================================================
C PROCEDURE: SOS_TRPHI_MULTI
C ==========
C      Fast recombination of the Fourier series decomposition of the
C      Stokes parameters I, Q and U for a list of relative azimuths.
C
C      The OS result file is read only ONCE: all the orders IS of the
C      Fourier series are kept in memory, then recombined for each
C      azimuth phi of the list:
C
C         I(mu,phi) = I0(mu) + 2 * SUM_IS  I_IS(mu) * cos(IS*phi)
C         Q(mu,phi) = Q0(mu) + 2 * SUM_IS  Q_IS(mu) * cos(IS*phi)
C         U(mu,phi) = U0(mu) + 2 * SUM_IS  U_IS(mu) * sin(IS*phi)
C
C      cos(IS*phi) and sin(IS*phi) are computed once per (IS, phi).
C      The direct reflection of the solar beam by the surface (glitter,
C      Fresnel, Roujean, Rondeaux, Breon, Nadal, Maignan), which is
C      removed from the OS computation, is then added analytically for
C      each azimuth by SOS_TRPHI_DIRECT.
C
C      The results are identical to NPHI calls of SOS_TRPHI (version
C      <= 8.2), which re-read the whole OS file for each azimuth.
C
C Description of parameters
C --------------------------
C     FICHOS (CHARACTER*CTE_LENFIC2) (I) : Name of the OS result file
C     NBMU (I4) (I) : Number of actually useful (positive) angles
C     RMU(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) (double) (I) :
C                     Cosines of the angles.
C     AT_DIR(CTE_OS_NBMU_MAX) (double) (I) : Direct transmission of
C                     the solar beam from TOA to the surface, then from
C                     the surface to the output level along the
C                     direction J (J = 1..NBMU).
C                     For a CKD computation, it is the CKD-weighted sum
C                     of the transmissions of each term (see SOS_PROC).
C     NPHI (I4) (I) : Number of relative azimuths.
C     PHI_LIST(NPHI) (double) (I) : Relative azimuths in radians.
C     IGLI ... COEF_C_MAIGNAN, IPOLAR (I) : see SOS_TRPHI.
C     XIT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,NPHI) (double) (O) :
C                     Stokes parameter I versus mu and azimuth.
C                        mu < 0 : downward field.
C                        mu > 0 : upward field.
C     XQT, XUT (double) (O) : Stokes parameters Q and U (same shape).
C     ANGDIFF(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,NPHI) (double) (O) :
C                     Scattering angles (degrees).
C     IER (I4) (O) : error code =0 if no error, =-1 otherwise
C
C Error cases:
C ------------
C     - Opening / reading of the OS result file.
C     - More than CTE_OS_NS_MAX+1 orders in the OS result file.
C==============================================================================
      SUBROUTINE SOS_TRPHI_MULTI(FICHOS,NBMU,RMU,AT_DIR,NPHI,PHI_LIST,
     &                     IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &                     IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &                     IRONDEAUX,IBREON,
     &                     INADAL,ALPHA_NADAL,BETA_NADAL,
     &                     IMAIGNAN,COEF_C_MAIGNAN,
     &                     IPOLAR,XIT,XQT,XUT,ANGDIFF,IER)

      IMPLICIT NONE

      CHARACTER*CTE_LENFIC2 FICHOS
      INTEGER*4 NBMU, NPHI, N0, IER
      INTEGER*4 IGLI, IFRESNEL, IROUJEAN, IRONDEAUX, IBREON
      INTEGER*4 INADAL, IMAIGNAN, IPOLAR
      DOUBLE PRECISION RMU(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION AT_DIR(CTE_OS_NBMU_MAX)
      DOUBLE PRECISION PHI_LIST(NPHI)
      DOUBLE PRECISION WIND, IND_SURF
      DOUBLE PRECISION K0_ROUJEAN, K1_ROUJEAN, K2_ROUJEAN
      DOUBLE PRECISION ALPHA_NADAL, BETA_NADAL, COEF_C_MAIGNAN
      DOUBLE PRECISION XIT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,NPHI)
      DOUBLE PRECISION XQT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,NPHI)
      DOUBLE PRECISION XUT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,NPHI)
      DOUBLE PRECISION ANGDIFF(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,NPHI)

C     Fourier coefficients of all the orders IS (read once)
      DOUBLE PRECISION I3S(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,
     &                     0:CTE_OS_NS_MAX)
      DOUBLE PRECISION Q3S(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,
     &                     0:CTE_OS_NS_MAX)
      DOUBLE PRECISION U3S(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,
     &                     0:CTE_OS_NS_MAX)

      DOUBLE PRECISION PHI    ! Current relative azimuth (radians)
      DOUBLE PRECISION XPHI   ! Product IS * PHI
      DOUBLE PRECISION CPHI   ! cos(IS*PHI)
      DOUBLE PRECISION SPHI   ! sin(IS*PHI)
      DOUBLE PRECISION C0     ! Cosine of the solar zenith angle
      DOUBLE PRECISION COSDIF ! Cosine of the scattering angle

      INTEGER*4 NS ! Highest order of the Fourier series in the file
      INTEGER*4 IS ! Order of the Fourier series
      INTEGER*4 J  ! Index of the angles
      INTEGER*4 IP ! Index of the azimuths

      IER=0

C* Reading of all the orders of the OS result file
C* (written with array bounds limited to -NBMU:NBMU)
C------------------------------------------------------------------
      OPEN(UNIT=16,FILE=FICHOS,FORM='UNFORMATTED',
     &      STATUS='OLD',ERR=991)

      NS=-1
      DO IS=0,CTE_OS_NS_MAX
         READ(16,END=5,ERR=992) (Q3S(J,IS),J=-NBMU,NBMU),
     &                          (U3S(J,IS),J=-NBMU,NBMU),
     &                          (I3S(J,IS),J=-NBMU,NBMU)
         NS=IS
      ENDDO
C     No order is expected beyond CTE_OS_NS_MAX
      READ(16,END=5,ERR=992)
      GOTO 993

    5 CLOSE(16)
      IF (NS.LT.0) GOTO 992

C* Recombination for each azimuth
C------------------------------------------------------------------
      C0 = RMU(N0)

      DO IP=1,NPHI

         PHI = PHI_LIST(IP)

C        Scattering angle for the different observation directions
         DO J= -NBMU, NBMU
            COSDIF = -C0*RMU(J)
     &              +SIN(ACOS(C0))*SIN(ACOS(RMU(J)))*DCOS(PHI)
            ANGDIFF(J,IP) = ACOS(COSDIF)*180.D+00/INCTE_PI
         ENDDO

C        Order IS = 0
         DO J= -NBMU, NBMU
            IF (J.EQ.0) THEN
               XQT(J,IP) = 0.D+00
               XUT(J,IP) = 0.D+00
               XIT(J,IP) = 0.D+00
            ELSE
               XQT(J,IP) = Q3S(J,0)
               XUT(J,IP) = U3S(J,0)
               XIT(J,IP) = I3S(J,0)
            ENDIF
         ENDDO

C        Orders IS = 1 to NS
         DO IS=1,NS
            XPHI = IS*PHI
            CPHI = DCOS(XPHI)
            SPHI = DSIN(XPHI)
            DO J= -NBMU, NBMU
               IF (J.NE.0) THEN
                  XQT(J,IP) = XQT(J,IP) +2.*Q3S(J,IS)*CPHI
                  XUT(J,IP) = XUT(J,IP) +2.*U3S(J,IS)*SPHI
                  XIT(J,IP) = XIT(J,IP) +2.*I3S(J,IS)*CPHI
               ENDIF
            ENDDO
         ENDDO

C        Direct reflection of the solar beam by the surface
         CALL SOS_TRPHI_DIRECT(NBMU,RMU,AT_DIR,PHI,
     &        IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &        IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &        IRONDEAUX,IBREON,
     &        INADAL,ALPHA_NADAL,BETA_NADAL,
     &        IMAIGNAN,COEF_C_MAIGNAN,IPOLAR,
     &        XIT(-CTE_OS_NBMU_MAX,IP),XQT(-CTE_OS_NBMU_MAX,IP),
     &        XUT(-CTE_OS_NBMU_MAX,IP))

      ENDDO !IP

C* Nominal end
C-------------------
      GOTO 9999

C* Error cases: return of status -1 to the calling program
C------------------------------------------------------
  991 WRITE(6,*) "SOS_TRPHI_MULTI : Error while opening a file"
      IER=-1
      GOTO 9999
  992 WRITE(6,*)
     &  "SOS_TRPHI_MULTI : Error while reading or writing on a file"
      IER=-1
      CLOSE(16)
      GOTO 9999
  993 WRITE(6,*)
     &  "SOS_TRPHI_MULTI : more Fourier orders than CTE_OS_NS_MAX"
      IER=-1
      CLOSE(16)
      GOTO 9999

 9999 CONTINUE

      RETURN  	!END OF PROCEDURE SOS_TRPHI_MULTI
      END



C==============================================================================
C PROCEDURE: SOS_TRPHI_DIRECT
C ==========
C      Adds, for one relative azimuth PHI, the reflection of the direct
C      solar beam by the surface (removed from the OS computations to
C      reduce the maximum useful order of the decomposition) to the
C      Stokes vector recombined from the Fourier series:
C         - Glitter (Cox and Munk rough sea)  : IGLI = 1
C         - Fresnel flat sea (direction N0)   : IFRESNEL = 1
C         - Roujean BRDF                      : IROUJEAN = 1
C         - Rondeaux, Breon or Maignan BPDF   : IRONDEAUX, IBREON,
C                                               IMAIGNAN = 1
C         - Nadal BPDF                        : INADAL = 1
C      Then the too small polarisation terms are set to zero.
C
C      Extracted from SOS_TRPHI (version 8.2). The attenuation of the
C      direct beam is given by AT_DIR (see SOS_TRPHI_MULTI).
C
C Description of parameters
C --------------------------
C     NBMU, RMU, AT_DIR, IGLI ... IPOLAR (I) : see SOS_TRPHI_MULTI.
C     PHI (double) (I) : Relative azimuth in radians.
C     XIT, XQT, XUT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX) (double) (I/O) :
C                        Stokes parameters for the azimuth PHI.
C==============================================================================
      SUBROUTINE SOS_TRPHI_DIRECT(NBMU,RMU,AT_DIR,PHI,
     &                     IGLI,N0,WIND,IND_SURF,IFRESNEL,
     &                     IROUJEAN,K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &                     IRONDEAUX,IBREON,
     &                     INADAL,ALPHA_NADAL,BETA_NADAL,
     &                     IMAIGNAN,COEF_C_MAIGNAN,IPOLAR,
     &                     XIT,XQT,XUT)

      IMPLICIT NONE

      INTEGER*4 NBMU, N0
      INTEGER*4 IGLI, IFRESNEL, IROUJEAN, IRONDEAUX, IBREON
      INTEGER*4 INADAL, IMAIGNAN, IPOLAR
      DOUBLE PRECISION RMU(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION AT_DIR(CTE_OS_NBMU_MAX)
      DOUBLE PRECISION PHI
      DOUBLE PRECISION WIND, IND_SURF
      DOUBLE PRECISION K0_ROUJEAN, K1_ROUJEAN, K2_ROUJEAN
      DOUBLE PRECISION ALPHA_NADAL, BETA_NADAL, COEF_C_MAIGNAN
      DOUBLE PRECISION XIT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION XQT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)
      DOUBLE PRECISION XUT(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX)

      DOUBLE PRECISION C0, S0  ! Cosine / sine of the solar zenith angle
      DOUBLE PRECISION C1, S1  ! Cosine / sine of the viewing angle
      DOUBLE PRECISION S12     ! Sin(Teta0) * Sin(Teta1)
      DOUBLE PRECISION ATJ     ! Direct transmission for direction J
      DOUBLE PRECISION SIGMA2  ! Square of Sigma (Cox and Munk)
      DOUBLE PRECISION P       ! Reflection probability / BPDF factor
      DOUBLE PRECISION COSDIF  ! Cosine of the scattering angle
      DOUBLE PRECISION COSKIP  ! Cosine of the rotation angle ki'
      DOUBLE PRECISION R11, R12, R33  ! Fresnel matrix (reflection plane)
      DOUBLE PRECISION M11, M21, M31  ! Reflection matrix (meridian plane)
      DOUBLE PRECISION COEF_SUN ! Solar radiance at TOA for Es = PI
      DOUBLE PRECISION PHIRJ   ! Azimuth with the Roujean convention
      DOUBLE PRECISION F       ! Roujean BRDF * cos(incidence angle)
      DOUBLE PRECISION F21FRESNEL ! Fresnel F21
      DOUBLE PRECISION F21NADAL   ! Nadal F21
      INTEGER*4 J

C* Addition of the direct reflection of the solar beam on the sea.
C-----------------------------------------------------------------
      IF (IGLI.EQ.1) THEN

         C0 = RMU(N0)

C* Square of the parameter Sigma of the Cox and Munk theory.
         SIGMA2 = .003 + .00512*WIND

         DO 101 J=1,NBMU
            C1=RMU(J)

C* Probability P of reflection in the direction J (wave slopes)
            CALL SOS_GLITTE(SIGMA2,C0,C1,PHI,P)

C* Scattering and rotation angles.
            CALL SOS_ANGLE(C0,C1,PHI,COSKIP,COSDIF)

C* Fresnel reflection matrix in the reflection plane.
            CALL SOS_REFLEX(COSDIF,IND_SURF,R11,R12,R33)

C* Fresnel reflection matrix in the meridian plane (rotation).
            CALL SOS_MATRIC(COSKIP,R11,R12,M11,M21,M31)

C* Direct reflection for a normalised solar irradiance (PI)
C* attenuated (ATJ) with the probability P of the wave slopes.
            ATJ = AT_DIR(J)
            XIT(J)= XIT(J)+M11*ATJ*P

            IF(IPOLAR.EQ.1) THEN
               XQT(J)= XQT(J)+M21*ATJ*P
               XUT(J)= XUT(J)+M31*ATJ*P
            ENDIF

  101    CONTINUE

      ENDIF	!Test igli=1


C* Addition of the reflection of the direct solar beam on a flat sea
C-----------------------------------------------------------------
      IF (IFRESNEL.EQ.1) THEN

C* Only in the solar principal plane and if the solar zenith angle
C* belongs to the output angles.
          IF ((DCOS(PHI).EQ.1.D+00).AND.(N0.GT.0)) THEN

              C0  = RMU(N0)

C* Transmission for the incidence and reflection directions
              ATJ = AT_DIR(N0)

C* Fresnel reflection matrix for the solar incidence
              COSDIF = 1. - 2.*C0*C0
              CALL SOS_REFLEX(COSDIF,IND_SURF,R11,R12,R33)

C* Solar radiance at TOA (Es=PI): Ls = Es/solid_angle_of_the_disc
              COEF_SUN = INCTE_PI / CTE_SOLAR_DISC_SOLID_ANGLE

              XIT(N0) = XIT(N0) + R11*COEF_SUN*ATJ
              IF(IPOLAR.EQ.1) XQT(N0) = XQT(N0) + R12*COEF_SUN*ATJ

          ENDIF

      ENDIF     !Test ifresnel=1


C* Addition of the reflection of the direct solar beam for the
C* Roujean BRDF
C-----------------------------------------------------------------
      IF (IROUJEAN.EQ.1) THEN

         C0 = RMU(N0)
         S0 = DSQRT(1.D+00-C0*C0)

         DO 103 J=1,NBMU

            C1 = RMU(J)
            ATJ = AT_DIR(J)
            S1 = DSQRT(1.D+00-C1*C1)

C*     Roujean BRDF (normalised radiance*cos(tetav))
            PHIRJ = INCTE_PI - PHI
            CALL SOS_CALC_F_ROUJEAN(K0_ROUJEAN,K1_ROUJEAN,K2_ROUJEAN,
     &                              C0,S0,C1,S1,PHIRJ,F)

            XIT(J)= XIT(J) + ATJ*F/C1

  103    CONTINUE

      ENDIF     !Test iroujean=1


C* Addition of the reflection of the direct solar beam for the
C* Rondeaux, Breon or Maignan BPDF
C-----------------------------------------------------------------
      IF( (IRONDEAUX.EQ.1).OR.(IBREON.EQ.1).OR.(IMAIGNAN.EQ.1) )  THEN

         C0 = RMU(N0)
         S0 = DSQRT(1.D+00-C0*C0)

         DO 105 J=1,NBMU

            C1 = RMU(J)
            ATJ = AT_DIR(J)

            CALL SOS_ANGLE(C0,C1,PHI,COSKIP,COSDIF)
            CALL SOS_REFLEX(COSDIF,IND_SURF,R11,R12,R33)
            CALL SOS_MATRIC(COSKIP,R11,R12,M11,M21,M31)

            IF (IRONDEAUX.EQ.1) P = 1. / ( 4.*(1+C1/C0) ) ! Rondeaux
            IF (IBREON.EQ.1) P = 1. / ( 4.*C1 )            ! Breon
            IF (IMAIGNAN.EQ.1) THEN
               S1 = DSQRT(1.D+00-C1*C1)
               S12 = S0*S1
               CALL SOS_CALCG_MAIGNAN(C0,C1,S12,PHI,COEF_C_MAIGNAN,P)
               P = P / ( 4.*C1 )                           ! Maignan
            ENDIF

            XIT(J)= XIT(J)+M11*ATJ*P
            IF(IPOLAR.EQ.1) THEN
               XQT(J)= XQT(J)+M21*ATJ*P
               XUT(J)= XUT(J)+M31*ATJ*P
            ENDIF

  105    CONTINUE

      ENDIF     !Test irondeaux or ibreon or imaignan = 1


C* Addition of the reflection of the direct solar beam for the
C* Nadal BPDF
C-----------------------------------------------------------------
      IF (INADAL.EQ.1) THEN

         C0 = RMU(N0)

         DO 107 J=1,NBMU

            C1 = RMU(J)
            ATJ = AT_DIR(J)

            CALL SOS_ANGLE(C0,C1,PHI,COSKIP,COSDIF)
            CALL SOS_REFLEX(COSDIF,IND_SURF,R11,R12,R33)
            CALL SOS_MATRIC(COSKIP,R11,R12,M11,M21,M31)

C*         Fresnel F21 (Nadal sign convention)
            F21FRESNEL = -R12

C*         Nadal F21
            F21NADAL = -BETA_NADAL * F21FRESNEL / (C0 + C1)
            F21NADAL = ALPHA_NADAL * ( 1.D+00 - DEXP(F21NADAL) )

            IF(F21FRESNEL.LT.1.0D-10) THEN ! Limited expansion near 0
               P = ALPHA_NADAL*BETA_NADAL / (C0 + C1)
            ELSE
               P = F21NADAL / F21FRESNEL
            ENDIF

            XIT(J)= XIT(J)+M11*ATJ*P
            IF(IPOLAR.EQ.1) THEN
               XQT(J)= XQT(J)+M21*ATJ*P
               XUT(J)= XUT(J)+M31*ATJ*P
            ENDIF

  107    CONTINUE

      ENDIF     !Test inadal=1


C******************************************************************
C* Polarisation terms that are too small are set to zero
C* --> Avoids rounding errors (non-zero U) from PHI=0 to PHI=PI
C* Term I set to zero if below 1.E-99.
C******************************************************************
      DO J= -NBMU,NBMU
         IF (XIT(J).LE.1.D-99) XIT(J)=0.D+00
         IF (DABS(XQT(J)).LT.CTE_THRESHOLD_Q_U_NULL) XQT(J)=0.D+00
         IF (DABS(XUT(J)).LT.CTE_THRESHOLD_Q_U_NULL) XUT(J)=0.D+00
      ENDDO

      RETURN  	!END OF PROCEDURE SOS_TRPHI_DIRECT
      END



