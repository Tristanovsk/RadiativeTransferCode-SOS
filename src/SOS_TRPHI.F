C==============================================================================
C PROCEDURE: SOS_POLAR
C ==========
C      Routine computing the polarisation angle, the degree of polarisation
C      and the polarised intensity for an input vector (I,Q,U)
C
C      The polarisation angle XAN is defined from -PI/2 to +PI/2.
C
C      The cases Q>0 and Q<0 are derived from the analysis of the values of
C      cos(2*XAN) and sin(2*XAN) together with the definition domain of XAN.
C
C      The case Q = 0 is derived from the possible values of XAN for Q = 0.
C      Q = U = 0 corresponds to no polarisation ==> Undefined angle.
C
C Description of parameters
C ------------------------------
C
C     XI (double)     (I) : Value of the Stokes parameter I
C     XQ (double)     (I) : Value of the Stokes parameter Q
C     XU (double)     (I) : Value of the Stokes parameter U
C     XAN (double)    (O) : Value of the polarisation angle (degrees)
C     TPOL (double)   (O) : Value of the degree of polarisation (%)
C     LPOL (double)   (O) : Polarised intensity normalised to the solar irradiance at TOA
C                           (PI * Lpol(z) / Esun)	       
C
C Common used:
C --------------
C None
C
C Error cases:
C --------------
C None
C
C  Subroutines used:
C -------------------------
C None
C
C
C MOD:VERSION:1.0: 22/08/2022: Initial version of the SOS-ABS code 
C    Imported from OSOAA V1.6 (routine version 1.1: 04/06/2018)
C
C==============================================================================

      SUBROUTINE SOS_POLAR(XI,XQ,XU,XAN,TPOL,LPOL)

      IMPLICIT NONE     
                       	    
C* Definition of variables
C*-----------------------------------------------------------------
      
      DOUBLE PRECISION XI ! (I) Stokes parameter I
      DOUBLE PRECISION XQ ! (I) Stokes parameter Q.
      DOUBLE PRECISION XU ! (I) Stokes parameter U.
      
      DOUBLE PRECISION XT ! Ratio U / Q
     					     
      DOUBLE PRECISION XAN ! (O) Polarisation angle (degrees)
	
      DOUBLE PRECISION LPOL ! (O) Polarised intensity normalised to the solar irradiance at TOA
      DOUBLE PRECISION TPOL ! (O) Degree of polarisation in %.
	

C* Processing
C*------------      
      
      IF (XQ.NE.0.) THEN !Case XQ!=0
 
         XT= XU/XQ
		 
         IF (XQ.GT.0.) THEN ! Case XQ > 0

            XAN= 90.*ATAN(XT)/INCTE_PI    
   
         ELSE ! Case XQ < 0

	     IF (XU.GT.0.) THEN
               XAN=90.+90.*DATAN(XT)/INCTE_PI
            ELSE
              XAN= -90.+90.*DATAN(XT)/INCTE_PI
            ENDIF

         ENDIF             

      ELSE !Case XQ=0

          IF (XU.GT.0.) THEN
              XAN=  45.
          ELSE
             IF (XU.LT.0) THEN
                XAN= -45.
             ELSE !Case XQ=XU undefined
                XAN= INCTE_VALEUR_INDEF
             ENDIF
          ENDIF

      ENDIF
	
      LPOL = SQRT(XQ*XQ+XU*XU)
      
      IF (XI.NE.0.D+00) THEN
         TPOL = 100.*LPOL/XI
      ELSE
         TPOL = INCTE_VALEUR_INDEF
      ENDIF
            
9999  RETURN   
            
      END      !END OF PROCEDURE SOS_POLAR
      
