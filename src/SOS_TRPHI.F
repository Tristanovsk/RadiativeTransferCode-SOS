C ==========
C      Copies the column IP (one azimuth) of the arrays produced by
C      SOS_TRPHI_MULTI into one-azimuth arrays.
C==============================================================================
      SUBROUTINE SOS_TRPHI_COLUMN(NBMU,IP,XITM,XQTM,XUTM,ANGM,
     &                            XIT,XQT,XUT,ANGDIFF)

      IMPLICIT NONE

      INTEGER*4 NBMU, IP, J
      DOUBLE PRECISION XITM(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,*)
      DOUBLE PRECISION XQTM(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,*)
      DOUBLE PRECISION XUTM(-CTE_OS_NBMU_MAX:CTE_OS_NBMU_MAX,*)
